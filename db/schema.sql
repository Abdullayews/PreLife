CREATE TABLE gym_workout_exercises (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day_id         bigint NOT NULL REFERENCES gym_workout_days(id) ON DELETE CASCADE,
  exercise_code  text NOT NULL REFERENCES gym_exercises(code) ON DELETE CASCADE,
  sets           int NOT NULL CHECK (sets >= 1),
  reps_type      text NOT NULL CHECK (reps_type IN ('reps', 'time', 'secs', 'each')),
  reps_a         int NOT NULL,
  reps_b         int,                                  -- range upper bound
  rest_seconds   int NOT NULL DEFAULT 0,
  sort_order     int NOT NULL DEFAULT 0
);

-- V1 mock progress ("week N of M") per plan.
CREATE TABLE gym_plan_progress (
  plan_id bigint PRIMARY KEY REFERENCES world_plans(id) ON DELETE CASCADE,
  week    int NOT NULL CHECK (week >= 1),
  total   int NOT NULL CHECK (total >= 1)
);

