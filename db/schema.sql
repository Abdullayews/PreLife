-- ═══════════════════════════════════════════════════════════════════════════
-- GROUP 5 — Psychology (psychologists, media, quizzes, rotations)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE psychologists (
  slug        text PRIMARY KEY,
  name_key    text NOT NULL,
  title_key   text NOT NULL,
  bio_key     text NOT NULL,
  image_url   text NOT NULL,
  rating      numeric(2,1) NOT NULL,
  price       numeric(6,2) NOT NULL,    -- AZN per 50-minute session
  initials    text NOT NULL,
  since_year  int  NOT NULL,
  edu_key     text NOT NULL,            -- education + career paragraph
  rules_key   text NOT NULL,            -- session rules paragraph
  sort_order  int  NOT NULL DEFAULT 0,
  is_active   bool NOT NULL DEFAULT true
);

CREATE TABLE psych_specialties (
  code       text PRIMARY KEY,          -- individual, couples, …
  sort_order int NOT NULL DEFAULT 0
);

CREATE TABLE psychologist_specialties (
  psychologist_slug text NOT NULL REFERENCES psychologists(slug) ON DELETE CASCADE,
  specialty_code    text NOT NULL REFERENCES psych_specialties(code) ON DELETE CASCADE,
  sort_order        int NOT NULL DEFAULT 0,
  PRIMARY KEY (psychologist_slug, specialty_code)
);

CREATE TABLE psychologist_formats (
  psychologist_slug text NOT NULL REFERENCES psychologists(slug) ON DELETE CASCADE,
  format            psy_format NOT NULL,
  sort_order        int NOT NULL DEFAULT 0,
  PRIMARY KEY (psychologist_slug, format)
);

CREATE TABLE psychologist_languages (
  psychologist_slug text NOT NULL REFERENCES psychologists(slug) ON DELETE CASCADE,
  lang              text NOT NULL,      -- 'az', 'en', 'ru'
  sort_order        int NOT NULL DEFAULT 0,
  PRIMARY KEY (psychologist_slug, lang)
);

-- Weekly recurring working blocks, Baku wall-clock hours (1 = Mon … 6 = Sat).
CREATE TABLE psychologist_availability (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  psychologist_slug text NOT NULL REFERENCES psychologists(slug) ON DELETE CASCADE,
  day               int NOT NULL CHECK (day BETWEEN 1 AND 6),
  from_hour         int NOT NULL CHECK (from_hour BETWEEN 0 AND 23),
  to_hour           int NOT NULL CHECK (to_hour BETWEEN 1 AND 24),
  sort_order        int NOT NULL DEFAULT 0,
  CHECK (from_hour < to_hour)
);

CREATE TABLE psychologist_certificates (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  psychologist_slug text NOT NULL REFERENCES psychologists(slug) ON DELETE CASCADE,
  cert_key          text NOT NULL,      -- psychApp message key
  sort_order        int NOT NULL DEFAULT 0
);

