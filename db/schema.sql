-- ═══════════════════════════════════════════════════════════════════════════
-- PreLife — Supabase PostgreSQL schema (full static content + user data)
--
-- Design principles:
--   • Content tables store STRUCTURE + NUMBERS + message keys; every
--     translatable string lives in i18n_messages (az/en/ru) — the site's
--     existing message-key architecture, now fully database-driven.
--   • Proper nouns (addresses, brand names, trainer names, author names,
--     store URLs) are locale-independent and stored inline.
--   • Full referential integrity (FKs), explicit sort_order everywhere,
--     is_active flags, updated_at triggers, sensible indexes.
--   • RLS enabled on every table with NO policies: only the service_role
--     (the Rust backend) can read/write through PostgREST.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Enums ──────────────────────────────────────────────────────────────────

CREATE TYPE content_level      AS ENUM ('beginner', 'intermediate', 'advanced');
CREATE TYPE store_kind         AS ENUM ('online', 'store', 'pharmacy');
CREATE TYPE product_category   AS ENUM ('equipment', 'supplements', 'accessories', 'clothing');
CREATE TYPE media_kind         AS ENUM ('audio', 'video');
CREATE TYPE media_collection   AS ENUM ('practice', 'tdb');
CREATE TYPE psy_format         AS ENUM ('online', 'office');
CREATE TYPE appointment_mode   AS ENUM ('online', 'office');
CREATE TYPE appointment_status AS ENUM ('upcoming', 'cancelled');
CREATE TYPE appointment_pay    AS ENUM ('unpaid', 'paid');

-- ── Shared trigger: updated_at ────────────────────────────────────────────

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ═══════════════════════════════════════════════════════════════════════════
-- GROUP 1 — i18n catalog (every visible string on the site)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE i18n_messages (
  key       text PRIMARY KEY,          -- dotted path, e.g. 'gymApp.plan.weekLabel'
  value_az  text NOT NULL,
  value_en  text NOT NULL,
  value_ru  text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_i18n_updated BEFORE UPDATE ON i18n_messages
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ═══════════════════════════════════════════════════════════════════════════
-- GROUP 2 — Content worlds (public welcome pages, all four sections)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE worlds (
  id             text PRIMARY KEY,      -- gym | diet | meditation | library
  ns             text NOT NULL,         -- message namespace (gymHome, …)
  anchor_plans   text NOT NULL,
  anchor_items   text NOT NULL,
  anchor_places  text NOT NULL,
  prefix_items   text NOT NULL,
  prefix_places  text NOT NULL,
  hero_images    text[] NOT NULL,       -- 3 hero photo URLs
  hero_positions text[] NOT NULL,       -- matching CSS object positions
  hero_stats     jsonb NOT NULL,        -- [[valueKey,labelKey] ×3]
  initials       text[] NOT NULL,       -- testimonial avatar initials
  sort_order     int  NOT NULL DEFAULT 0,
  is_active      bool NOT NULL DEFAULT true
);

CREATE TABLE world_plans (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id   text NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  slug       text NOT NULL,
  name_key   text NOT NULL,
  desc_key   text NOT NULL,
  image_url  text NOT NULL,
  level      content_level NOT NULL,
  featured   bool NOT NULL DEFAULT false,
  sort_order int NOT NULL DEFAULT 0,
  UNIQUE (world_id, slug)
);

CREATE TABLE world_plan_meta (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id    bigint NOT NULL REFERENCES world_plans(id) ON DELETE CASCADE,
  meta_key   text NOT NULL,             -- ICU message key (count-capable)
  value      int  NOT NULL,
  sort_order int  NOT NULL DEFAULT 0
);

CREATE TABLE world_items (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id   text NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  slug       text NOT NULL,             -- exercise/recipe/session/book id
  name_key   text NOT NULL,
  target_key text NOT NULL,
  icon       text NOT NULL,             -- Lucide icon name (client registry)
  level      content_level NOT NULL,
  sort_order int NOT NULL DEFAULT 0,
  UNIQUE (world_id, slug)
);

CREATE TABLE world_cando (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id   text NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  icon       text NOT NULL,
  title_key  text NOT NULL,
  desc_key   text NOT NULL,
  sort_order int NOT NULL DEFAULT 0
);

CREATE TABLE world_schedule_slots (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id   text NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  time       text NOT NULL,             -- '07:00'
  label_key  text NOT NULL,
  sort_order int NOT NULL DEFAULT 0
);

CREATE TABLE world_schedule_cells (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_id    bigint NOT NULL REFERENCES world_schedule_slots(id) ON DELETE CASCADE,
  day_index  int  NOT NULL,             -- 0 = Mon … 5 = Sat
  cell_code  text NOT NULL              -- references world_schedule_kinds.code
);

CREATE TABLE world_schedule_kinds (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id   text NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  code       text NOT NULL,
  label_key  text NOT NULL,
  sort_order int NOT NULL DEFAULT 0,
  UNIQUE (world_id, code)
);

CREATE TABLE world_places (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id   text NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  slug       text NOT NULL,
  name_key   text NOT NULL,
  desc_key   text NOT NULL,
  image_url  text NOT NULL,
  rating     numeric(2,1) NOT NULL,
  sort_order int NOT NULL DEFAULT 0,
  UNIQUE (world_id, slug)
);

CREATE TABLE world_place_features (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id     bigint NOT NULL REFERENCES world_places(id) ON DELETE CASCADE,
  feature_key  text NOT NULL,           -- message key (feat247, featSauna, …)
  sort_order   int NOT NULL DEFAULT 0
);

-- ═══════════════════════════════════════════════════════════════════════════
-- GROUP 3 — Gym (partner halls, equipment, trainers, shop, workouts)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE gym_places (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug            text NOT NULL UNIQUE,
  ns              text NOT NULL CHECK (ns IN ('gymHome', 'gymApp')),
