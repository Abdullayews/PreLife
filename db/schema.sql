-- ═══════════════════════════════════════════════════════════════════════════
-- GROUP 8 — User data (auth, sessions, appointments, journal, mood, …)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE users (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email         text NOT NULL UNIQUE,
  name          text,
  password_hash text NOT NULL,          -- scrypt 'salt:hash' (hex), Node-compatible
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- One row per signed-in device; cookie carries the raw token, only its
-- SHA-256 hex hash is stored. Sliding 1-year expiry.
CREATE TABLE sessions (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash   text NOT NULL UNIQUE,
  device_name  text NOT NULL,
  device_icon  text NOT NULL DEFAULT 'monitor',
  user_agent   text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE appointments (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id           uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  psychologist_slug text NOT NULL REFERENCES psychologists(slug),
  start_at          timestamptz NOT NULL,  -- UTC instant of Baku date+hour
  mode              appointment_mode   NOT NULL DEFAULT 'online',
  price             numeric(6,2) NOT NULL, -- AZN, frozen at booking time
  status            appointment_status NOT NULL DEFAULT 'upcoming',
  payment           appointment_pay    NOT NULL DEFAULT 'unpaid',
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_appt_user_start ON appointments(user_id, start_at);
CREATE INDEX idx_appt_psy_start  ON appointments(psychologist_slug, start_at);

CREATE TABLE mood_logs (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date       text NOT NULL,             -- Baku calendar day 'YYYY-MM-DD'
  mood       int NOT NULL CHECK (mood BETWEEN 1 AND 5),
  energy     int NOT NULL CHECK (energy BETWEEN 1 AND 5),
  sleep_q    int NOT NULL CHECK (sleep_q BETWEEN 1 AND 5),
  tags       text NOT NULL DEFAULT '',  -- comma-separated message keys
  note       text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, date)
);
CREATE TRIGGER trg_mood_updated BEFORE UPDATE ON mood_logs
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE quiz_results (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  quiz_id    text NOT NULL REFERENCES quizzes(code),
  score      int NOT NULL,
  max_score  int NOT NULL,
  answers    jsonb NOT NULL DEFAULT '[]', -- array of 0–3 answers
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_quiz_user ON quiz_results(user_id, quiz_id);

CREATE TABLE journal_entries (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  prompt_key text,                       -- psychApp journal prompt key
  content    text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_journal_user ON journal_entries(user_id, created_at DESC);
CREATE TRIGGER trg_journal_updated BEFORE UPDATE ON journal_entries
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE meditation_progress (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  resource_id text NOT NULL REFERENCES media_resources(id),
  kind       media_kind NOT NULL,
  seconds    int NOT NULL CHECK (seconds BETWEEN 1 AND 7200),
  completed  bool NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_medprog_user ON meditation_progress(user_id, created_at);

-- ═══════════════════════════════════════════════════════════════════════════
-- Row Level Security: everything locked down; the Rust backend connects as
-- service_role (bypasses RLS). No anon access to any table.
-- ═══════════════════════════════════════════════════════════════════════════

DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END;
$$;

-- Grant table access to service_role (PostgREST uses the roles above RLS).
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO service_role', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
  END LOOP;
END;
$$;
