  sort_order      int  NOT NULL DEFAULT 0
);

CREATE TABLE gym_place_features (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_place_id  bigint NOT NULL REFERENCES gym_places(id) ON DELETE CASCADE,
  feature_key   text NOT NULL,
  sort_order    int NOT NULL DEFAULT 0
);

CREATE TABLE gym_equipment (
  code       text PRIMARY KEY,          -- powerRacks, treadmills, …
  name_key   text NOT NULL,             -- gymApp.hallEq.<code>
  sort_order int NOT NULL DEFAULT 0
);

CREATE TABLE gym_place_equipment (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_place_id    bigint NOT NULL REFERENCES gym_places(id) ON DELETE CASCADE,
  equipment_code  text NOT NULL REFERENCES gym_equipment(code) ON DELETE CASCADE,
  sort_order      int NOT NULL DEFAULT 0,
  UNIQUE (gym_place_id, equipment_code)
);

CREATE TABLE gym_trainer_specs (
  code       text PRIMARY KEY,          -- strength, yoga, physio, …
  name_key   text NOT NULL,             -- gymApp.hallSpec.<code>
  sort_order int NOT NULL DEFAULT 0
);

CREATE TABLE gym_trainers (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_place_id  bigint NOT NULL REFERENCES gym_places(id) ON DELETE CASCADE,
  name          text NOT NULL,          -- proper noun
  spec_code     text NOT NULL REFERENCES gym_trainer_specs(code),
  years         int  NOT NULL CHECK (years >= 0),
  sort_order    int NOT NULL DEFAULT 0
);

CREATE TABLE gym_stores (
  slug       text PRIMARY KEY,          -- tap, unimall, …
  name       text NOT NULL,             -- proper noun
  kind       store_kind NOT NULL,
  url        text NOT NULL,
  sort_order int NOT NULL DEFAULT 0
);

CREATE TABLE gym_products (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category   product_category NOT NULL,
  slug       text NOT NULL,
  name_key   text NOT NULL,             -- gymApp.<category>.<nameKey>
  brand      text NOT NULL,             -- proper noun
  icon       text NOT NULL,             -- Lucide icon name (registry)
  price_min  numeric(8,2) NOT NULL,
  price_max  numeric(8,2) NOT NULL,
  image_url  text,
  sort_order int NOT NULL DEFAULT 0,
  UNIQUE (category, slug)
);

CREATE TABLE gym_product_offers (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  bigint NOT NULL REFERENCES gym_products(id) ON DELETE CASCADE,
  store_slug  text NOT NULL REFERENCES gym_stores(slug) ON DELETE CASCADE,
  price       numeric(8,2) NOT NULL,
  sort_order  int NOT NULL DEFAULT 0
);

CREATE TABLE gym_exercises (
  code       text PRIMARY KEY,          -- run, squat, bench, …
  name_key   text NOT NULL,
  target_key text NOT NULL,
  guide_key  text NOT NULL,
  sort_order int NOT NULL DEFAULT 0
);

-- Weekly workout structure, attached to the gym world's plans.
CREATE TABLE gym_workout_days (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id    bigint NOT NULL REFERENCES world_plans(id) ON DELETE CASCADE,
  day        int  NOT NULL CHECK (day BETWEEN 1 AND 7), -- 1 = Mon … 7 = Sun
  sort_order int  NOT NULL DEFAULT 0,
  UNIQUE (plan_id, day)
